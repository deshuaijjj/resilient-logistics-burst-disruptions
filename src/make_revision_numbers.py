        macro('NominalFullWorstB', fmt(nom['complete_library_worst_recourse'] / B, 9)),
        macro('NominalUnmet', fmt_int(nom['worst_unmet_tons'])),
        macro('NominalWorstID', str(nom['worst_scenario_id'])),
        macro('VerifyExactWorstM', fmt(d['exact']['complete_library_worst_recourse'] / M, 6)),
        macro('VerifyExactTotalB', fmt(d['exact']['complete_library_total_cost'] / B, 9)),
        macro('VerifySampledWorstM', fmt(d['sampled']['complete_library_worst_recourse'] / M, 6)),
        macro('VerifyNominalWorstM', fmt(nom['complete_library_worst_recourse'] / M, 6)),
        macro('VerifyExactMaximizers', str(d['exact']['num_cost_maximizers_within_tolerance'])),
        macro('VerifySampledMaximizers', str(d['sampled']['num_cost_maximizers_within_tolerance'])),
        macro('VerifyExactMaximizerIDs', ' and '.join(str(i) for i in d['exact']['cost_maximizers_within_tolerance'])),
        macro('VerifyEvalTimeS', fmt(d['exact']['eval_time_s'], 1)),
        macro('AuditDominated', fmt_int(d['exact']['monotonicity_audit']['dominated_matrices_checked'])),
        macro('AuditPairs', fmt_int(d['exact']['monotonicity_audit']['comparable_pairs_checked'])),
        macro('AuditViolations', str(sum(v['monotonicity_audit']['violations'] for v in d.values()))),
