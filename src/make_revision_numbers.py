        macro('LOOQTwo', fmt(loo['design']['q'][2], 1)),
        macro('LOOFullB', fmt(loo['complete_library_total_cost'] / B, 3)),
        macro('LOOOmitPct', fmt(loo['probability_uniform_sample_of_999_maximal_matrices_omits_it_pct'], 1)),
        macro('MaxDurationEvents', str(sup['closed_form_maximal_set']['maximum_duration_events'])),
