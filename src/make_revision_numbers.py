"""Generate LaTeX macros for the September 2026 revision numbers from results/12-23.

The manuscript inputs ``sections/revision_numbers.tex``,
``sections/revision_seeds_table.tex`` and ``sections/revision_libsens_table.tex``;
regenerating them from the artifacts is
the only way new numbers enter the paper, so every printed value traces to a
JSON/CSV file by construction.

Usage:
  python3 src/make_revision_numbers.py --results-root results \
      --out-dir paper/ieee_aerospace_2027/sections
"""

from __future__ import annotations

import argparse
