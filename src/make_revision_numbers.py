            macro('RerunCCGSepS', fmt(ccg['separation_time_total_s'], 2)),
            macro('RerunCCGWallS', fmt(ccg['wall_time_s'], 2)),
            macro('RerunCCGLPs', fmt_int(ccg['recourse_lps'])),
            macro('RerunCCGObjB', fmt(ccg['final_upper_bound'] / B, 9)),
