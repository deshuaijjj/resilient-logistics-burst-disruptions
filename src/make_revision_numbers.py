    # ---- CCG from the nominal encoding (results/21) ------------------------------------
    cs = load(os.path.join(R, '21_ccg_start_sets', 'ccg_start_sets.json'))
    cmax, call = cs['nominal_start_maximal_separation'], cs['nominal_start_all_encoding_separation']
